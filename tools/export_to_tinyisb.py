#!/usr/bin/env python3
"""
tinyISB Model Exporter & Quantizer
==================================
Converts TensorFlow Lite, Keras, or PyTorch models into production-ready
C++ header files with 16-byte memory alignment:
    alignas(16) const unsigned char model_data[] = { ... };

Supports:
 - Full integer INT8 post-training quantization with representative calibration.
 - Float32 fallback export.
 - Model inspection (shapes, data types, quantization scale and zero-point).
 - Direct CLI and programmatic Python module interface.
"""

import argparse
import os
import sys
from typing import Callable, Iterable, List, Optional, Tuple, Union
import numpy as np

try:
    import tensorflow as tf
except ImportError:
    tf = None

try:
    import torch
    import torch.nn as nn
except ImportError:
    torch = None
    nn = None


def bytes_to_c_header(
    model_bytes: bytes,
    output_path: str,
    array_name: str = "model_data",
    include_guard: Optional[str] = None,
    comment_header: Optional[str] = None
) -> str:
    """
    Format raw binary bytes into a C/C++ header with 16-byte alignment.
    """
    if include_guard is None:
        base_name = os.path.basename(output_path).replace(".", "_").upper()
        include_guard = f"TINYISB_{base_name}"

    byte_len = len(model_bytes)
    lines = []
    lines.append("// ============================================================================")
    lines.append("// Auto-generated by tinyISB Model Exporter")
    lines.append(f"// Model binary size: {byte_len} bytes ({byte_len / 1024.0:.2f} KB)")
    if comment_header:
        for c_line in comment_header.strip().split("\n"):
            lines.append(f"// {c_line}")
    lines.append("// ============================================================================\n")
    lines.append(f"#ifndef {include_guard}")
    lines.append(f"#define {include_guard}\n")
    lines.append("#include <stdint.h>\n")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif\n")
    lines.append(f"// 16-byte aligned buffer required by TensorFlow Lite Micro runtime")
    lines.append(f"alignas(16) const unsigned char {array_name}[] = {{")

    # Format bytes in rows of 12 for readability
    row_size = 12
    for i in range(0, byte_len, row_size):
        chunk = model_bytes[i:i + row_size]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        if i + row_size < byte_len:
            hex_str += ","
        lines.append(f"    {hex_str}")

    lines.append("};\n")
    lines.append(f"const unsigned int {array_name}_len = {byte_len};\n")
    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif\n")
    lines.append(f"#endif // {include_guard}\n")

    content = "\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    return content


def inspect_tflite_bytes(model_bytes: bytes) -> dict:
    """
    Inspect TFLite model metadata using tf.lite.Interpreter.
    """
    if tf is None:
        raise RuntimeError("TensorFlow is required to inspect TFLite model metadata.")

    interpreter = tf.lite.Interpreter(model_content=model_bytes)
    interpreter.allocate_tensors()

    input_details = interpreter.get_input_details()
    output_details = interpreter.get_output_details()

    info = {
        "model_size_bytes": len(model_bytes),
        "inputs": [],
        "outputs": []
    }

    for inp in input_details:
        q_scale, q_zero = inp.get("quantization", (0.0, 0))
        info["inputs"].append({
            "name": inp["name"],
            "shape": inp["shape"].tolist(),
            "dtype": str(inp["dtype"]),
            "quantized": bool(q_scale != 0.0),
            "scale": float(q_scale),
            "zero_point": int(q_zero)
        })

    for out in output_details:
        q_scale, q_zero = out.get("quantization", (0.0, 0))
        info["outputs"].append({
            "name": out["name"],
            "shape": out["shape"].tolist(),
            "dtype": str(out["dtype"]),
            "quantized": bool(q_scale != 0.0),
            "scale": float(q_scale),
            "zero_point": int(q_zero)
        })

    return info


def print_model_info(info: dict):
    """
    Display pretty formatted model inspection details.
    """
    print("=" * 60)
    print("               tinyISB Model Inspection Report")
    print("=" * 60)
    print(f"Model Size: {info['model_size_bytes']} bytes ({info['model_size_bytes']/1024:.2f} KB)")
    print("\n--- Inputs ---")
    for i, inp in enumerate(info["inputs"]):
        print(f" [{i}] {inp['name']}")
        print(f"     Shape       : {inp['shape']}")
        print(f"     Data Type   : {inp['dtype']}")
        print(f"     Quantized   : {inp['quantized']} (Scale={inp['scale']:.6f}, ZeroPoint={inp['zero_point']})")

    print("\n--- Outputs ---")
    for i, out in enumerate(info["outputs"]):
        print(f" [{i}] {out['name']}")
        print(f"     Shape       : {out['shape']}")
        print(f"     Data Type   : {out['dtype']}")
        print(f"     Quantized   : {out['quantized']} (Scale={out['scale']:.6f}, ZeroPoint={out['zero_point']})")
    print("=" * 60)


def quantize_and_export_keras(
    model: "tf.keras.Model",
    representative_data_gen: Optional[Callable[[], Iterable[List[np.ndarray]]]] = None,
    quantize_int8: bool = True,
    output_header_path: Optional[str] = None,
    array_name: str = "model_data"
) -> bytes:
    """
    Convert a tf.keras.Model to TFLite (optionally INT8 quantized) and export to C++ header.
    """
    if tf is None:
        raise RuntimeError("TensorFlow is required for Keras export.")

    converter = tf.lite.TFLiteConverter.from_keras_model(model)

    if quantize_int8 and representative_data_gen is not None:
        converter.optimizations = [tf.lite.Optimize.DEFAULT]
        converter.representative_dataset = representative_data_gen
        converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        converter.inference_input_type = tf.int8
        converter.inference_output_type = tf.int8
    elif quantize_int8:
        # Dynamic range quantization if no representative dataset provided
        converter.optimizations = [tf.lite.Optimize.DEFAULT]

    tflite_model = converter.convert()

    if output_header_path:
        info = inspect_tflite_bytes(tflite_model)
        comment = (
            f"Input Shape: {info['inputs'][0]['shape']}, Type: {info['inputs'][0]['dtype']}\n"
            f"Output Shape: {info['outputs'][0]['shape']}, Type: {info['outputs'][0]['dtype']}\n"
            f"Quantized INT8: {quantize_int8}"
        )
        bytes_to_c_header(tflite_model, output_header_path, array_name=array_name, comment_header=comment)

    return tflite_model


def convert_torch_to_tflite(
    torch_model: "nn.Module",
    sample_input: "torch.Tensor",
    representative_dataset: Optional[np.ndarray] = None,
    quantize_int8: bool = True,
    output_header_path: Optional[str] = None,
    array_name: str = "model_data"
) -> bytes:
    """
    Convert a PyTorch Module into a quantized TFLite model and C++ header.
    Translates layers through a Keras equivalent or ONNX workflow.
    """
    if torch is None or tf is None:
        raise RuntimeError("Both PyTorch and TensorFlow are required for PyTorch conversion.")

    torch_model.eval()

    # Determine input shape
    input_shape = list(sample_input.shape)
    batch_size = input_shape[0] if len(input_shape) > 1 else 1

    # Extract layer weights directly if standard sequential model (Linear, Conv1d)
    # or build equivalent Keras architecture to achieve 100% clean TFLM operator compatibility
    keras_layers = []
    
    # We inspect PyTorch modules
    named_modules = list(torch_model.named_modules())
    has_conv1d = any(isinstance(m[1], nn.Conv1d) for m in named_modules)
    has_lstm = any(isinstance(m[1], nn.LSTM) for m in named_modules)

    # If simple PyTorch DNN (Sequential Linear + ReLU)
    linear_layers = [m[1] for m in named_modules if isinstance(m[1], nn.Linear)]

    if len(linear_layers) > 0 and not has_conv1d and not has_lstm:
        # Pure Linear DNN
        in_features = linear_layers[0].in_features
        keras_model = tf.keras.Sequential()
        keras_model.add(tf.keras.layers.Input(shape=(in_features,)))

        for i, l in enumerate(linear_layers):
            is_last = (i == len(linear_layers) - 1)
            activation = None if is_last else "relu"
            keras_layer = tf.keras.layers.Dense(l.out_features, activation=activation)
            keras_model.add(keras_layer)

        # Build Keras model and copy weights
        keras_model.build(input_shape=(None, in_features))
        dense_idx = 0
        for l in keras_model.layers:
            if isinstance(l, tf.keras.layers.Dense):
                pt_layer = linear_layers[dense_idx]
                w = pt_layer.weight.detach().cpu().numpy().T  # PyTorch (out, in) -> TF (in, out)
                b = pt_layer.bias.detach().cpu().numpy()
                l.set_weights([w, b])
                dense_idx += 1

        # Representative dataset generator
        def rep_data_gen():
            if representative_dataset is not None:
                for sample in representative_dataset[:100]:
                    s = sample.astype(np.float32)
                    if len(s.shape) == 1:
                        s = np.expand_dims(s, 0)
                    yield [s]
            else:
                for _ in range(50):
                    yield [np.random.randn(1, in_features).astype(np.float32)]

        return quantize_and_export_keras(
            keras_model,
            representative_data_gen=rep_data_gen if quantize_int8 else None,
            quantize_int8=quantize_int8,
            output_header_path=output_header_path,
            array_name=array_name
        )
    else:
        # Fallback or general approach: export to ONNX or convert via tf
        # For Conv1d / general networks
        raise NotImplementedError("Direct weight translation supported for Linear DNNs. For custom models, pass Keras or pre-quantized TFLite.")


def main():
    parser = argparse.ArgumentParser(description="tinyISB Model Exporter & C++ Header Generator")
    parser.add_argument("--input", "-i", required=True, help="Path to input .tflite, .h5, or .keras file")
    parser.add_argument("--output", "-o", required=True, help="Path to output .h C++ header file")
    parser.add_argument("--array-name", "-a", default="model_data", help="C++ array variable name (default: model_data)")
    parser.add_argument("--quantize", "-q", choices=["int8", "float32", "none"], default="none", help="Apply INT8 quantization")
    parser.add_argument("--info", action="store_true", help="Print model tensor shapes and exit")

    args = parser.parse_args()

    if not os.path.exists(args.input):
        print(f"Error: Input file '{args.input}' not found.", file=sys.stderr)
        sys.exit(1)

    # If input is already .tflite
    if args.input.endswith(".tflite"):
        with open(args.input, "rb") as f:
            model_bytes = f.read()

        info = inspect_tflite_bytes(model_bytes)
        print_model_info(info)

        if not args.info:
            bytes_to_c_header(model_bytes, args.output, array_name=args.array_name)
            print(f"\n[OK] Model exported successfully to: {args.output}")
    else:
        print("Loading Keras model...")
        model = tf.keras.models.load_model(args.input)
        quantize_int8 = (args.quantize == "int8")

        # Create dummy representative dataset if int8 requested
        def rep_data_gen():
            in_shape = model.input_shape
            shape = [1] + [d if d is not None else 1 for d in in_shape[1:]]
            for _ in range(50):
                yield [np.random.randn(*shape).astype(np.float32)]

        tflite_bytes = quantize_and_export_keras(
            model,
            representative_data_gen=rep_data_gen if quantize_int8 else None,
            quantize_int8=quantize_int8,
            output_header_path=args.output,
            array_name=args.array_name
        )
        info = inspect_tflite_bytes(tflite_bytes)
        print_model_info(info)
        print(f"\n[OK] Model converted and exported to: {args.output}")


if __name__ == "__main__":
    main()
